import { CronJobItem, TimelineRun, CollisionEvent, DensitySlot, TimelineStats } from './types';
import {
  parseCron,
  getRunsBetween,
  formatTimeInZone,
  formatDateInZone,
  formatRelativeTime,
  RangeOptions,
} from './cronEngine';
import { JOB_COLORS } from './presets';

export interface StatsOptions {
  jobs: CronJobItem[];
  runs24h: TimelineRun[];
  runs7d: TimelineRun[];
  collisions: CollisionEvent[];
}

export function generateJobRuns(
  jobs: CronJobItem[],
  range: RangeOptions,
  timezone: string
): TimelineRun[] {
  const allRuns: TimelineRun[] = [];
  const now = new Date();

  jobs
    .filter((j) => j.enabled)
    .forEach((job) => {
      const parsed = parseCron(job.expression);
      if (!parsed.valid) return;
      const dates = getRunsBetween(parsed, range);

      dates.forEach((date) => {
        allRuns.push({
          jobId: job.id,
          jobName: job.name,
          color: job.color,
          date,
          timestamp: date.getTime(),
          formattedTime: formatTimeInZone(date, timezone),
          formattedDate: formatDateInZone(date, timezone),
          relativeTime: formatRelativeTime(now, date),
        });
      });
    });

  return allRuns.sort((a, b) => a.timestamp - b.timestamp);
}

export function detectCollisions(
  runs: TimelineRun[],
  jobMap: Map<string, CronJobItem>
): CollisionEvent[] {
  const groups = new Map<number, TimelineRun[]>();
  runs.forEach((run) => {
    const list = groups.get(run.timestamp) ?? [];
    list.push(run);
    groups.set(run.timestamp, list);
  });

  const collisions: CollisionEvent[] = [];
  groups.forEach((runList, timestamp) => {
    const uniqueJobIds = new Set(runList.map((r) => r.jobId));
    if (uniqueJobIds.size > 1) {
      const first = runList[0];
      collisions.push({
        timestamp,
        timeString: first.formattedTime,
        dateString: first.formattedDate,
        jobs: Array.from(uniqueJobIds).map((id) => {
          const job = jobMap.get(id);
          return {
            jobId: id,
            jobName: job?.name ?? 'Unknown',
            color: job?.color ?? '#888',
            expression: job?.expression ?? '* * * * *',
          };
        }),
      });
    }
  });

  return collisions.sort((a, b) => a.timestamp - b.timestamp);
}

export function calculateHourlyDensity(runs: TimelineRun[]): DensitySlot[] {
  const slots: DensitySlot[] = Array.from({ length: 24 }, (_, i) => ({
    hour: i,
    count: 0,
    jobs: [],
  }));

  runs.forEach((run) => {
    const hour = parseInt(run.formattedTime.slice(0, 2), 10) % 24;
    const slot = slots[hour];
    if (slot) {
      slot.count += 1;
      let jobEntry = slot.jobs.find((j) => j.jobId === run.jobId);
      if (!jobEntry) {
        jobEntry = { jobId: run.jobId, jobName: run.jobName, count: 0, color: run.color };
        slot.jobs.push(jobEntry);
      }
      jobEntry.count += 1;
    }
  });

  return slots;
}

function findShortestInterval(runs: TimelineRun[]): number | null {
  if (runs.length < 2) return null;
  let minDiff = Infinity;
  for (let i = 1; i < runs.length; i += 1) {
    const diff = Math.floor((runs[i].timestamp - runs[i - 1].timestamp) / 60000);
    if (diff > 0 && diff < minDiff) minDiff = diff;
  }
  return minDiff === Infinity ? null : minDiff;
}

export function calculateTimelineStats(opts: StatsOptions): TimelineStats {
  const density = calculateHourlyDensity(opts.runs24h);
  let busiestHour: number | null = null;
  let maxCount = 0;

  density.forEach((slot) => {
    if (slot.count > maxCount) {
      maxCount = slot.count;
      busiestHour = slot.hour;
    }
  });

  return {
    totalJobs: opts.jobs.length,
    activeJobs: opts.jobs.filter((j) => j.enabled).length,
    runs24h: opts.runs24h.length,
    runs7d: opts.runs7d.length,
    busiestHour,
    collisionCount: opts.collisions.length,
    shortestIntervalMinutes: findShortestInterval(opts.runs24h),
  };
}

export function exportCrontabFormat(jobs: CronJobItem[]): string {
  const lines: string[] = ['# Generated by Toolnest Crontab Visualizer', '#'];
  jobs.forEach((job) => {
    if (!job.enabled) lines.push(`# [DISABLED] ${job.name}`);
    else lines.push(`# ${job.name}`);
    lines.push(`${job.expression} ${job.command || '/usr/local/bin/run-task'}`);
    lines.push('');
  });
  return lines.join('\n');
}

export function parseCrontabInput(raw: string): Omit<CronJobItem, 'id'>[] {
  const lines = raw.split('\n');
  const result: Omit<CronJobItem, 'id'>[] = [];
  let pendingComment = '';
  let colorIdx = 0;

  for (const rawLine of lines) {
    const line = rawLine.trim();
    if (!line) continue;
    if (line.startsWith('#')) {
      pendingComment = line.replace(/^#\s*/, '').replace(/\[DISABLED\]\s*/i, '');
      continue;
    }
    const parts = line.split(/\s+/);
    if (parts.length >= 5) {
      const expression = parts.slice(0, 5).join(' ');
      const command = parts.slice(5).join(' ');
      const name = pendingComment || `Job: ${expression}`;
      const color = JOB_COLORS[colorIdx % JOB_COLORS.length];
      colorIdx += 1;
      result.push({ name, expression, color, enabled: true, command });
      pendingComment = '';
    }
  }
  return result;
}
